export const getDefaultProfileFromEmployee = (
  employee: Employee,
  companyName: string
): UserProfileFull => ({
  userId: employee.id,
  header: {
    email: employee.email,
    phone: employee.phone || '',
    companyName,
    employeeId: employee.employeeId,
  },
  org: {
    businessUnit: employee.businessUnit || '-',
    department: employee.department,
    reportingManager: '-',
  },
  primaryDetails: {
    name: employee.name,
    displayName: employee.name.split(' ')[0],
    gender: '-',
    maritalStatus: '-',
    dateOfBirth: employee.dateOfBirth || '-',
    nationality: '-',
    physicallyHandicapped: false,
  },
  identification: {},
  addresses: employee.address
    ? [
        {
          line1: employee.address,
          city: '-',
          state: '-',
          pincode: '-',
          country: '-',
        },
      ]
    : [],
  contact: { phone: employee.phone || '' },
  education: [],
  pastExperience: [],
  timeline: [],
  jobDetail: {
    jobTitlePrimary: employee.designation,
    managerName: '-',
    employeeId: employee.employeeId,
    joiningDate: employee.joiningDate,
    workerType: '-',
    timeType: 'full',
  },
  employeeTime: {
    shift: '-',
    weeklyOffPolicy: '-',
    leavePlan: '-',
    holidayCalendar: '-',
    attendanceNumber: '-',
    payrollTimeSource: '-',
    disableAttendanceTracking: false,
    attendanceCaptureScheme: '-',
    attendancePenalisationPolicy: '-',
    attendanceTrackingPolicy: '-',
    shiftWeeklyOffRule: '-',
    shiftAllowancePolicy: '-',
    overtime: '-',
  },
  customFields: [
    ...(employee.location ? [{ label: 'Location', value: employee.location }] : []),
    ...(employee.costCenter ? [{ label: 'Cost Center', value: employee.costCenter }] : []),
    ...(employee.legalEntity ? [{ label: 'Legal Entity', value: employee.legalEntity }] : []),
    ...(employee.businessUnit ? [{ label: 'Business Unit', value: employee.businessUnit }] : []),
  ],
});

